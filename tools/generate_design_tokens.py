#!/usr/bin/env python3
"""Regenerate native color constants from the imported, reviewable token JSON."""
from pathlib import Path
import json
import argparse

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "app/src/main/kotlin/cn/wpgd/app/ui/DesignTokens.kt"

def rendered():
    tokens = json.loads((ROOT / "design/tokens.json").read_text())
    lines = ["// Generated by tools/generate_design_tokens.py; edit design/tokens.json instead.",
             "package cn.wpgd.app.ui", "", "import androidx.compose.ui.graphics.Color", "", "object DesignTokens {"]
    for mode in ["light", "dark"]:
        lines.append(f"    val {mode}: Map<String, Color> = mapOf(")
        for token in tokens["colors"]:
            value = token[mode]
            if len(value) != 7 or not value.startswith("#"):
                raise ValueError(f"Unsupported color {value}")
            int(value[1:], 16)
            lines.append(f'        "{token["name"]}" to Color(0xFF{value[1:]}),')
        lines.append("    )")
    # Type scale (sp), spacing scale (dp) and radii (dp), so composables reference tokens by name.
    lines.append("    val typeSp: Map<String, Int> = mapOf(")
    for name, value in tokens["typography_sp"].items():
        lines.append(f'        "{name}" to {int(value)},')
    lines.append("    )")
    lines.append("    val spacingDp: List<Int> = listOf(" + ", ".join(str(int(v)) for v in tokens["spacing_dp"]) + ")")
    lines.append("    val radiiDp: Map<String, Int> = mapOf(")
    for name, value in tokens["radii_dp"].items():
        lines.append(f'        "{name}" to {int(value)},')
    lines.append("    )")
    return "\n".join(lines + ["}", ""])

if __name__ == "__main__":
    parser = argparse.ArgumentParser(); parser.add_argument("--check", action="store_true"); args = parser.parse_args()
    content = rendered()
    if args.check:
        if not DEST.exists() or DEST.read_text() != content:
            raise SystemExit("Native design tokens are stale; run tools/generate_design_tokens.py")
        print("Native colors match the design token JSON.")
    else:
        DEST.write_text(content)
        print("Generated", DEST.relative_to(ROOT))
